cd "$(dirname "$0")"
OUTDIR="$(cd ../world/生图集 && pwd)"
MODEL=doubao-seedream-5.0-lite

gen() {
  local name="$1"; local prompt="$2"
  echo ">>> $name"
  ARKCLI_CALLER_TYPE=ai_agent ARKCLI_CALLER_NAME=pi ARKCLI_SKILL_NAME=arkcli-gen \
  arkcli +gen --model "$MODEL" --modality image --size 4K --save-to "$OUTDIR" "$prompt" 2>&1 | grep -E '"local_path"|"status"|"message"' | head -3
  sleep 3
}

