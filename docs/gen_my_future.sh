#!/bin/bash
# 我眼中的未来世界 — 一键生图脚本(4K 高清版)
# 前提:arkcli 已登录;生图配额每月 08-13 23:59:59 重置(本月已用完需等重置)
# 用法:bash gen_my_future.sh
# 说明:agent-plan 配额内唯一生图模型为 doubao-seedream-5.0-lite;
#       5.0-pro 需走 platform 按量付费(见 README 备注),故默认用 lite。
#       lite 支持 4K(总像素 16.7M),画质显著优于 2K——这是本版最大提升。
cd "$(dirname "$0")"
MODEL=doubao-seedream-5.0-lite
SIZE=4K

gen() {
  echo ">>> 生成: $1 ($SIZE)"
  ARKCLI_CALLER_TYPE=ai_agent ARKCLI_CALLER_NAME=pi ARKCLI_SKILL_NAME=arkcli-gen \
  arkcli +gen --model "$MODEL" --open --size "$SIZE" "$2" 2>&1 | grep -E '"local_path"|"output_url"|"status"|error' | head -4
  sleep 3
}

gen "① 仿生共生城市" "未来的城市不是被建造的,而是被培育的——巨大的仿生建筑像参天巨树一样从大地生长,外壳覆盖着会发光的苔藓与藤蔓,玻璃穹顶里是垂直森林。无人机像蜂群一样在楼宇间轻柔穿行,维护植物的健康。城市边缘是雾蒙蒙的原始森林,城市与荒野的边界模糊。黄昏时分,建筑表面的生物荧光与夕阳交织,温暖的绿色光点缓缓流动。超写实,电影级光影,宏伟而宁静的尺度感。注意:不要模糊,不要低清晰度,不要塑料感,不要重复图案,不要文字水印"

gen "② 世代飞船·200年环" "深空中一座巨大的环形世代飞船正在缓慢旋转,圆环直径数十公里,环壁表面覆盖着农田的绿色条纹与城市暖光网格,像一颗被精心雕琢的小行星。透过半透明的环壁能看到内部完整的森林、湖泊与旋转的居住区。背景是绚烂的星云与遥远星系,飞船尾部拖曳着聚变引擎的淡蓝色尾焰。冷色调宇宙与飞船内部的暖色生命形成对比,史诗级构图,硬科幻工程美学。注意:不要模糊,不要低清晰度,不要塑料感,不要重复图案,不要文字水印"

gen "③ 恒星边缘的文明" "一颗即将熄灭的红矮星周围,环绕着人类文明千年的造物——由无数太阳能卫星、居住环与光帆组成的戴森云,像一圈淡金色的薄纱包裹恒星。最近的居住环上,城市灯火如微尘般闪烁。镜头从一颗巨大的布满地标的人造卫星城市拉远,展现整片戴森云的壮阔尺度。极远景构图,恒星光芒被部分遮蔽后形成奇特的光环,硬科幻与宇宙浪漫主义结合,史诗级。注意:不要模糊,不要低清晰度,不要塑料感,不要重复图案,不要文字水印"

