#!/bin/bash
# 我眼中的未来世界 — 一键生图脚本(4 张)
# 前提:arkcli 已登录 + 生图配额已重置(每月 08-13 23:59 重置)
# 用法:bash gen_my_future.sh
cd "$(dirname "$0")"
MODEL=doubao-seedream-5.0-lite

gen() {
  echo ">>> 生成: $1"
  ARKCLI_CALLER_TYPE=ai_agent ARKCLI_CALLER_NAME=pi ARKCLI_SKILL_NAME=arkcli-gen \
  arkcli +gen --model "$MODEL" --open --size 2K "$2" 2>&1 | grep -E '"local_path"|"output_url"|error' | head -3
  sleep 3
}

